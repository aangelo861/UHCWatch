/**
 * Build the UHC Watch dashboards.
 *
 *   node src/build.mjs
 *
 * Reads data/snapshot.json (the copy of the UHC Watch API taken by
 * src/fetch.mjs, and the single source of every figure), renders every page
 * into docs/, compiles the stylesheet, copies nhsuk-frontend JavaScript,
 * writes the CSV and JSON downloads and checks internal links.
 */
import fs from 'node:fs'
import path from 'node:path'
import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import * as sass from 'sass'
import { setAssetVersion } from './lib/html.mjs'

import { loadSnapshot } from './lib/data.mjs'
import { createContext } from './lib/context.mjs'
import { site } from './lib/site.mjs'
import { checkLinks } from './lib/check-links.mjs'
import { buildHub } from './pages/hub.mjs'
import { buildCountriesIndex, buildCountryPages } from './pages/countries.mjs'
import { buildIndicatorsIndex, buildIndicatorPages } from './pages/indicators.mjs'
import { buildCompare, buildAbout } from './pages/misc.mjs'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const SNAPSHOT = path.join(ROOT, 'data', 'snapshot.json')
const OUT = path.join(ROOT, 'docs')
const MARKER = path.join(OUT, '.generated-by-build')
const NHSUK = path.join(ROOT, 'node_modules', 'nhsuk-frontend', 'dist', 'nhsuk')
const SCRIPTS = ['charts.js', 'app.js', 'compare.js']

function prepareOutputDir() {
  if (fs.existsSync(OUT)) {
    if (!fs.existsSync(MARKER) && fs.readdirSync(OUT).length) {
      throw new Error(`${OUT} exists and was not created by this build. Move it aside or delete it first.`)
    }
    fs.rmSync(OUT, { recursive: true, force: true })
  }
  fs.mkdirSync(OUT, { recursive: true })
  fs.writeFileSync(MARKER, 'This directory is generated by `npm run build`. Do not edit by hand.\n')
  fs.writeFileSync(path.join(OUT, '.nojekyll'), '')
}

function write(relPath, content) {
  const p = path.join(OUT, relPath)
  fs.mkdirSync(path.dirname(p), { recursive: true })
  fs.writeFileSync(p, content)
}

function main() {
  const db = loadSnapshot(SNAPSHOT)
  const ctx = createContext({ site, db })

  prepareOutputDir()

  // Stylesheet first, so pages can reference assets by content hash
  const css = sass.compile(path.join(ROOT, 'src', 'styles', 'app.scss'), {
    loadPaths: [path.join(ROOT, 'node_modules')],
    style: 'compressed',
    quietDeps: true
  }).css
  const jsSources = SCRIPTS.map((f) => fs.readFileSync(path.join(ROOT, 'src', 'js', f)))
  const assetVersion = createHash('sha256').update(css).update(Buffer.concat(jsSources)).digest('hex').slice(0, 10)
  setAssetVersion(assetVersion)

  const pages = [
    buildHub(ctx),
    buildCountriesIndex(ctx),
    ...buildCountryPages(ctx),
    buildIndicatorsIndex(ctx),
    ...buildIndicatorPages(ctx),
    buildCompare(ctx),
    buildAbout(ctx)
  ]

  let downloads = 0
  for (const p of pages) {
    write(p.page.url, p.html)
    if (p.csv) { write(p.csv.url, p.csv.text); downloads++ }
    if (p.json) write(p.json.url, JSON.stringify(p.json.value))
  }

  // Assets
  write('javascripts/nhsuk-frontend.min.js', fs.readFileSync(path.join(NHSUK, 'nhsuk-frontend.min.js')))
  SCRIPTS.forEach((f, i) => write(`javascripts/${f}`, jsSources[i]))
  const imagesDir = path.join(ROOT, 'src', 'assets', 'images')
  for (const f of fs.readdirSync(imagesDir)) {
    if (f.startsWith('.')) continue
    write(path.posix.join('assets/images', f), fs.readFileSync(path.join(imagesDir, f)))
  }

  // Stylesheet, and the nhsuk icons it references by URL
  write('stylesheets/app.css', css)
  for (const [, f] of css.matchAll(/url\("\.\.\/assets\/images\/([^"]+)"\)/g)) {
    write(path.posix.join('assets/images', f), fs.readFileSync(path.join(NHSUK, 'assets', 'images', f)))
  }

  // Link check
  const { files, errors } = checkLinks(OUT)
  console.log(`Built ${files} pages from the snapshot of ${ctx.snapshotDate} into docs/ (assets v=${assetVersion})`)
  console.log(`Downloads: ${downloads} CSV files.`)
  if (errors.length) {
    console.error(`\n${errors.length} broken internal link(s):`)
    for (const e of errors) console.error(`  - ${e}`)
    process.exitCode = 1
  } else {
    console.log('Internal links: all resolve.')
  }
}

main()
